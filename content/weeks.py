def trimester(week):
    return 1 if week <= 13 else (2 if week <= 27 else 3)


def get(week, lang):
    e = W[week]
    ms = lang == "ms"
    length, weight = e[3], e[4]
    if ms:
        length = length.replace("about", "lebih kurang")
        weight = weight.replace("about", "lebih kurang")
    return {
        "week": week,
        "emoji": e[0],
        "size": e[2] if ms else e[1],
        "length": length,
        "weight": weight,
        "baby": e[6] if ms else e[5],
        "mum": e[8] if ms else e[7],
        "todo": e[10] if ms else e[9],
        "tri": trimester(week),
    }
